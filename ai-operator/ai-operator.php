/*
 * Мониторинг:
 * 
 * - FPS: измеряется каждые 16мс
 * - Батарея: navigator.getBattery()
 * - Видимость страницы: visibilitychange
 * 
 * Состояния:
 * 
 * 1. perf.guard.high — всё включено
 * 2. perf.guard.low — аварийное отключение
 * 
 * Условия входа в low:
 * - FPS < 40
 * - Батарея < 15% и не заряжается
 * - Страница не в фокусе
 * 
 * Автоочистка:
 * - clearIntervalAll()
 * - clearTimeoutAll()
 * - disconnectAllObservers()
 * - closeAllWebSockets()
 * - cancelAllRaf()
 * 
 * Исключения:
 * - На /cart, /checkout, /search — эффекты не отключаются полностью
 */

